const { z } = require('zod');

const nullableString = (maxLength) =>
  z.preprocess(
    (value) => {
      if (value === '' || value === undefined) {
        return null;
      }

      return value;
    },
    z
      .string()
      .trim()
      .max(maxLength)
      .nullable(),
  );

const genericBodySchema = z.object({
  name: z
    .string({
      required_error: 'Generic name is required.',
    })
    .trim()
    .min(1, 'Generic name is required.')
    .max(255, 'Generic name is too long.'),

  code: nullableString(50),

  description: nullableString(65535),

  status: z
    .coerce
    .number()
    .int()
    .min(0)
    .max(1)
    .default(1),
});

const genericIdParamsSchema = z.object({
  id: z
    .coerce
    .number()
    .int()
    .positive()
    .max(Number.MAX_SAFE_INTEGER),
});

const genericListQuerySchema = z.object({
  status: z
    .coerce
    .number()
    .int()
    .min(0)
    .max(1)
    .default(1),

  search: z
    .string()
    .trim()
    .max(255)
    .optional()
    .default(''),
});

module.exports = {
  createGenericSchema: genericBodySchema,
  updateGenericSchema: genericBodySchema,
  genericIdParamsSchema,
  genericListQuerySchema,
};
